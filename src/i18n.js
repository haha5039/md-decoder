let locale;

export function getLocale() {
  if (locale) return locale;
  try { locale = typeof window === 'undefined' ? null : window.localStorage.getItem(STORAGE_KEY); } catch { /* Storage is optional. */ }
  if (!messages[locale]) locale = 'ko';
  return locale;
}

export function t(key, values = {}) {
  const template = messages[getLocale()]?.[key] ?? messages.ko[key] ?? key;
  return Object.entries(values).reduce((text, [name, value]) => text.replaceAll(`{${name}}`, String(value)), template);
}

export function setLocale(value) {
  locale = messages[value] ? value : 'ko';
  try { if (typeof window !== 'undefined') window.localStorage.setItem(STORAGE_KEY, locale); } catch { /* Storage is optional. */ }
  if (typeof document !== 'undefined') document.documentElement.lang = locale;
}

export function localizeCardName(card) {
  if (!card) return '';
  return getLocale() === 'en' ? (card.nameEn || card.name) : (card.name || card.nameEn);
}

export function alternateCardName(card) {
  if (!card) return '';
  return getLocale() === 'en' ? (card.name || '') : (card.nameEn || '');
}

export function applyDocumentTranslations(root = document) {
  document.documentElement.lang = getLocale();
  document.title = t(document.body?.dataset.i18nTitle || 'app.title');
  root.querySelectorAll('[data-i18n]').forEach(element => { element.textContent = t(element.dataset.i18n); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach(element => { element.placeholder = t(element.dataset.i18nPlaceholder); });
  root.querySelectorAll('[data-i18n-title]').forEach(element => { element.title = t(element.dataset.i18nTitle); });
  root.querySelectorAll('[data-i18n-aria-label]').forEach(element => { element.setAttribute('aria-label', t(element.dataset.i18nAriaLabel)); });
}

export function initializeI18n(onChange) {
  applyDocumentTranslations();
  const select = document.getElementById('localeSelect');
  if (!select) return;
  select.value = getLocale();
  select.addEventListener('change', () => {
    setLocale(select.value);
    applyDocumentTranslations();
    onChange?.();
  });
}

export function populateLocalizedSelect(select, values, keyPrefix) {
  const current = select.value;
  select.innerHTML = `<option value="">${t('common.selectNone')}</option>`;
  for (const value of values) {
    const option = document.createElement('option');
    option.value = value;
    option.textContent = t(`${keyPrefix}.${value}`);
    select.appendChild(option);
  }
  if ([...select.options].some(option => option.value === current)) select.value = current;
}
